LOADER = Path(__file__).with_name("_loader.py")
MANIFEST = "manifest.json"  # in the outer zip, next to __main__.py
FIXED_TIME = (1980, 1, 1, 0, 0, 0)  # reproducible zips: same inputs, same bytes, same cache key
COMPILE_LOADER = """
import py_compile, sys
py_compile.compile(sys.argv[1], cfile=sys.argv[2], dfile="__main__.py", doraise=True,
                   invalidation_mode=py_compile.PycInvalidationMode.UNCHECKED_HASH)
"""


def _crc32(path: Path) -> int:
    """A file's CRC-32, as a zip records it."""
    crc = 0
    with path.open("rb") as f:
        while chunk := f.read(1 << 20):
            crc = zlib.crc32(chunk, crc)
    return crc


def render_loader(config: dict[str, object]) -> str:
    """The loader's source with its config block replaced by this bundle's values."""
    text = LOADER.read_text(encoding="utf-8")
    head, rest = text.split("# --- config: replaced at build time ---\n", 1)
    _, tail = rest.split("# --- end config ---\n", 1)
    lines = "".join(f"{k} = {v!r}\n" for k, v in config.items())
    return f"{head}# --- config (generated by bundleup) ---\n{lines}# --- end config ---\n{tail}"


def _compile_loader(target: Target, loader: Path, loader_pyc: Path, *, progress: Progress) -> None:
    """Compile `__main__.py` with the target interpreter, reusing cached bytecode across builds."""
    identity = (
        f"{_bytecode.FORMAT}-{target.implementation}-{target.full_version}-{target.cache_tag}"
    )
    key = hashlib.sha256(loader.read_bytes() + identity.encode()).hexdigest()[:32]
    cached = _bytecode.cache_dir() / f"loader-{key}.pyc"
    if cached.is_file():
        with contextlib.suppress(OSError):
            shutil.copyfile(cached, loader_pyc)
            return
    run(
        [target.executable, "-s", "-S", "-c", COMPILE_LOADER, str(loader), str(loader_pyc)],
        what="compiling the loader",
        progress=progress,
        error=BundleupError,
        env=compile_env(),
    )
    tmp = cached.with_name(f".{cached.name}.{os.getpid()}.{os.urandom(4).hex()}.tmp")
    try:
        cached.parent.mkdir(parents=True, exist_ok=True)
        shutil.copyfile(loader_pyc, tmp)
        tmp.replace(cached)
    except OSError:
        pass
    finally:
        with contextlib.suppress(OSError):
            tmp.unlink(missing_ok=True)


def _package_entry(pkg: _verify.LockedPackage, licenses: dict[str, str]) -> dict[str, object]:
    entry: dict[str, object] = {"name": pkg.name, "version": pkg.version}
    lic = licenses.get(pkg.name)
    if lic:
        entry["license"] = lic
    if pkg.origin:
        entry["origin"] = pkg.origin
    return entry


def manifest(
    *,
    source: Source,
    version: str | None,
    target: Target,
    native: bool,
    entry: Entry | None,
    cache_dir: str | None,
    fmt: Format,
    payload: Path | None,
    payload_sha256: str | None,
    locked: list[_verify.LockedPackage],
    files: dict[str, str],
    loader: dict[str, str] | None,
    pythons: PythonRange,
    reach: Portability,
    licenses: dict[str, str] | None = None,
) -> bytes:
    """What's inside the bundle, with hashes: read by `bundleup verify` and by reviewers
    (`unzip -p app.pyz manifest.json`). Sorted, so the same inputs give the same bytes."""
    lic_map = licenses or {}
    document = {
        "manifest_version": 1,
        "bundleup_version": __version__,
        "name": source.name,
        "version": version,
        "target": target.to_json_dict(native=native, pythons=pythons, reach=reach),
        "entry": list(entry) if entry else None,
        "cache_dir": cache_dir,
        "format": fmt,
        # The inner zip and the loader exist only in a .pyz; `files` covers every format.
        "payload": {"sha256": payload_sha256, "size": payload.stat().st_size} if payload else None,
        "loader": loader,  # __main__.py and __main__.pyc: they run first, so they're checked too
        "packages": [_package_entry(p, lic_map) for p in sorted(locked, key=lambda p: p.name)],
        "files": files,
    }
    return json.dumps(document, indent=1, sort_keys=True).encode("utf-8") + b"\n"


def _replace_with_retry(src: Path, dst: Path) -> None:
    """Atomically move `src` to `dst`, retrying brief Windows sharing/access locks held by
    real-time antivirus scanners on newly written archives or `.pyd`/`.dll` directories."""
    import errno
    import time

    delays = (0.02, 0.05, 0.1, 0.2, 0.4) if os.name == "nt" else ()
    attempt = 0
    while True:
        try:
            src.replace(dst)
            return
        except OSError as e:
            winerr = getattr(e, "winerror", None)
            transient = os.name == "nt" and (
                e.errno in (errno.EACCES, errno.EPERM) or winerr in (5, 32)
            )
            if not transient or attempt >= len(delays):
                raise
            time.sleep(delays[attempt])
            attempt += 1


@contextlib.contextmanager
def atomic_output(output: Path) -> Iterator[Path]:
    """Yield a temporary file next to `output` and atomically replace `output` when the block
    succeeds; on failure, remove the temporary file and any parent directories created for it."""
    created = [p for p in (output.parent, *output.parent.parents) if not p.exists()]
    output.parent.mkdir(parents=True, exist_ok=True)
    tmp = output.with_name(f".{output.name}.tmp-{os.getpid()}-{os.urandom(4).hex()}")
    wrote = False
    try:
        yield tmp
        _replace_with_retry(tmp, output)
        wrote = True
    finally:
        if tmp.exists():
            tmp.unlink()
        if not wrote:
            for d in created:
                with contextlib.suppress(OSError):
                    d.rmdir()


def write_bundle(
    output: Path,
    *,
    payloads: dict[str, Path],
    loader: Path,
    loader_pyc: Path,
    manifest_json: bytes,
    max_size: int | None = None,
    parts: str | None = None,
    split: int | None = None,
    diagnostics: list[Diagnostic] | None = None,
) -> None:
    """Write shebang + outer zip to a temporary file, then rename it over `output`. `payloads`:
    member name -> payload zip (one, `payload.zip`, unless the bundle is for several platforms).
    The finished file is checked against `max_size` before it replaces anything. With `parts`
    (`--split`), the payloads go into that folder beside `output` instead, written first."""
    folder = output.with_name(parts or f"{output.name}.parts")
    with atomic_output(output) as tmp:
        with open(tmp, "wb") as f:
            # Plain python3 (works everywhere, also with Windows' py launcher); a wrong version
            # re-runs itself with a matching one (ADR-0036).
            f.write(b"#!/usr/bin/env python3\n")
            with zipfile.ZipFile(f, "w", zipfile.ZIP_STORED) as zf:
                for member, payload in sorted(payloads.items()) if not parts else []:
                    info = zipfile.ZipInfo(member, FIXED_TIME)
                    info.external_attr = 0o100644 << 16
                    big = payload.stat().st_size >= min(0x7FFFFFFF, _zipwriter.LIMIT)
                    with open(payload, "rb") as src, zf.open(info, "w", force_zip64=big) as dest:
                        shutil.copyfileobj(src, dest, 1 << 20)
                for path, name in ((loader, "__main__.py"), (loader_pyc, "__main__.pyc")):
                    info = zipfile.ZipInfo(name, FIXED_TIME)
                    info.external_attr = 0o100644 << 16
                    info.compress_type = zipfile.ZIP_DEFLATED
                    zf.writestr(info, path.read_bytes())
                info = zipfile.ZipInfo(MANIFEST, FIXED_TIME)
                info.external_attr = 0o100644 << 16
                info.compress_type = zipfile.ZIP_DEFLATED  # can be MBs for big bundles
                zf.writestr(info, manifest_json)
        tmp.chmod(0o755)
        size = tmp.stat().st_size + sum(p.stat().st_size for p in payloads.values()) * bool(parts)
        check_size(size, max_size, list(diagnostics) if diagnostics is not None else [])
        if split is not None and tmp.stat().st_size > split:
            alone = " alone (its loader and manifest)" if parts else ""
            raise UsageError(
                f"the .pyz{alone} would be {describe_size(tmp.stat().st_size)}, over --split "
                f"{describe_size(split)}",
                hint="give --split a bigger size",
            )
        _replace_parts(folder, payloads if parts else None)


PART_NAME = re.compile(r"layer-[0-9a-f]{16}\.zip")


def _replace_parts(folder: Path, payloads: dict[str, Path] | None) -> None:
    """Write a split bundle's parts folder (a new one, renamed over the old), or remove a stale
    one an earlier `--split` build left beside the output. Never touches a folder that holds
    anything but parts."""
    ours = (
        folder.is_dir()
        and not folder.is_symlink()
        and all(PART_NAME.fullmatch(x.name) for x in folder.iterdir())
    )
    if (folder.exists() or folder.is_symlink()) and not ours:
        if payloads is None:
            return  # not ours, and not needed: leave it alone
        raise UsageError(
            f"{folder} already exists and isn't a parts folder bundleup wrote",
            hint="remove it, or choose another place with -o",
        )
    nonce = f"{os.getpid()}-{os.urandom(4).hex()}"
    old = folder.with_name(f".{folder.name}.old-{nonce}")
    new = folder.with_name(f".{folder.name}.tmp-{nonce}")
    try:
        if payloads is not None:
            new.mkdir()
            for member, payload in payloads.items():
                shutil.copyfile(payload, new / member)
        if folder.exists():
            _replace_with_retry(folder, old)
        if payloads is not None:
            _replace_with_retry(new, folder)
    finally:
        if new.exists():
            _loader._rmtree(str(new))
        if old.exists():
            _loader._rmtree(str(old))


